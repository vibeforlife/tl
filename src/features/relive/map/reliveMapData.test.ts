import { describe, expect, it } from 'vitest';
import type { RelivePresentation } from '../../../domain/relive';
import type { Entry } from '../../../types/domain';
import { buildReliveJourneyModel } from '../model/journeyPlaybackModel';
import { generateReliveJourneyRoutes, toReliveRouteGeoJsonGeometry } from '../model/reliveRouteGeometry';
import {
  createRelivePlaybackEngine,
  getRelivePlaybackSnapshot,
} from '../engine/relivePlaybackEngine';
import { buildReliveMapData, getReliveRouteBearing, getReliveUnwrappedStopCoordinates } from './reliveMapData';

const makeEntry = (
  id: string,
  date: string,
  latitude: number,
  longitude: number,
): Entry => ({
  id,
  title: `Memory ${id}`,
  date,
  location: { name: `Place ${id}`, latitude, longitude },
} as Entry);

const presentation: RelivePresentation = {
  journeyId: 'journey-map',
  title: 'Map integration',
  durationMode: 'journey',
  memoryCount: 2,
  estimatedDurationSeconds: 10,
  scenes: [
    { id: 'opening', type: 'opening', title: 'Opening', subtitle: 'Start', durationSeconds: 2 },
    { id: 'memory-a', type: 'memory', entryId: 'a', title: 'A', date: '2026-01-01', highlight: '', durationSeconds: 3 },
    { id: 'memory-b', type: 'memory', entryId: 'b', title: 'B', date: '2026-01-02', highlight: '', durationSeconds: 3 },
    { id: 'closing', type: 'closing', title: 'Closing', subtitle: 'End', durationSeconds: 2 },
  ],
};

describe('Relive map presentation data', () => {
  it('reveals the same generated route geometry used by the car position', () => {
    const entries = [
      makeEntry('a', '2026-01-01', 19.076, 72.877),
      makeEntry('b', '2026-01-02', 13.0827, 80.2707),
    ];
    const model = buildReliveJourneyModel(entries);
    const engine = createRelivePlaybackEngine(presentation, model);
    const snapshot = getRelivePlaybackSnapshot(engine, {
      cursorMs: 6500,
      status: 'playing',
    });
    const data = buildReliveMapData(engine, snapshot);

    expect(data.contextRoutes.features).toHaveLength(1);
    expect(data.travelledRoutes.features).toHaveLength(1);
    expect(data.travelledRoutes.features[0].properties.progress).toBe(0.5);

    const geometry = data.travelledRoutes.features[0].geometry;
    expect(geometry.type).toBe('LineString');
    if (geometry.type !== 'LineString') throw new Error('Expected a LineString');
    const lastRouteCoordinate = geometry.coordinates.at(-1);
    expect(lastRouteCoordinate?.[0]).toBeCloseTo(snapshot.carCoordinate?.[0] ?? NaN, 6);
    expect(lastRouteCoordinate?.[1]).toBeCloseTo(snapshot.carCoordinate?.[1] ?? NaN, 6);
    expect(Number.isFinite(data.carBearing)).toBe(true);
  });

  it('marks the active stop and preserves the route generated by the engine', () => {
    const entries = [
      makeEntry('a', '2026-01-01', 19.076, 72.877),
      makeEntry('b', '2026-01-02', 13.0827, 80.2707),
    ];
    const model = buildReliveJourneyModel(entries);
    const engine = createRelivePlaybackEngine(presentation, model);
    const snapshot = getRelivePlaybackSnapshot(engine, {
      cursorMs: 6500,
      status: 'playing',
    });
    const data = buildReliveMapData(engine, snapshot);

    expect(data.stops.features).toHaveLength(2);
    expect(data.stops.features.map((feature) => feature.properties.isActive)).toEqual([0, 1]);
    const expectedGeometry = toReliveRouteGeoJsonGeometry(
      engine.routes[model.legs[0].id].coordinates,
    );
    expect(data.contextRoutes.features[0].geometry).toEqual(expectedGeometry);
  });

  it('splits antimeridian route features for Mapbox while keeping camera bounds unwrapped', () => {
    const entries = [
      makeEntry('west', '2026-01-01', 10, 179),
      makeEntry('east', '2026-01-02', 11, -179),
    ];
    const model = buildReliveJourneyModel(entries);
    const routes = generateReliveJourneyRoutes(model.legs);
    const geometry = toReliveRouteGeoJsonGeometry(routes[model.legs[0].id].coordinates);
    expect(geometry.type).toBe('MultiLineString');

    const cameraCoordinates = getReliveUnwrappedStopCoordinates(
      model.stops.map((stop) => stop.coordinate),
    );
    expect(Math.abs(cameraCoordinates[1][0] - cameraCoordinates[0][0])).toBeLessThan(5);
  });

  it('returns no car bearing for a route with fewer than two points', () => {
    expect(getReliveRouteBearing([[10, 10]], 0.5)).toBeNull();
  });
});
